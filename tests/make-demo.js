/*
 * Writes js/demo.js: a run through world 1-1 found by the search-based player, which the title
 * screen plays when nobody touches the controls. Run with: node tests/make-demo.js
 *
 * The replay only holds button presses, so it must be made again whenever the physics or the map
 * of world 1-1 changes; `node tests/run.js` checks that it still reaches the flagpole.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const solver = require('./solver.js');

const result = solver.solve(0, { power: 0 });
if (!result.solved) throw new Error('no route through world 1-1 was found');

const bursts = result.bursts.join('');
const lines = [];
for (let i = 0; i < bursts.length; i += 80) lines.push("      '" + bursts.slice(i, i + 80) + "'");

const source = [
  '/* Generated by tests/make-demo.js: the button presses for the demo of world 1-1 on the title screen. */',
  '(function (SM) {',
  "  'use strict';",
  '',
  '  SM.DEMO = {',
  '    level: 0,',
  '    // Each digit picks one of `actions` and holds it for `burstFrames` frames.',
  '    burstFrames: ' + solver.BURST_FRAMES + ',',
  '    actions: [',
  solver.ACTIONS.map(function (a) {
    const keys = Object.keys(a);
    return '      {' + (keys.length ? ' ' + keys.map(function (k) {
      return k + ': true';
    }).join(', ') + ' ' : '') + '},';
  }).join('\n'),
  '    ],',
  '    bursts:',
  lines.join(' +\n') + ',',
  '  };',
  '})((globalThis.SM = globalThis.SM || {}));',
  '',
].join('\n');

fs.writeFileSync(path.join(__dirname, '..', 'js', 'demo.js'), source);
console.log('wrote js/demo.js: ' + bursts.length + ' bursts, ' + (result.inputs.length / 60).toFixed(1) + ' s');
