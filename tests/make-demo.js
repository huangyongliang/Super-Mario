/*
 * Writes js/demo.js: a run through every world found by the search-based player, which the title
 * screen plays in turn when nobody touches the controls. Run with: node tests/make-demo.js
 *
 * The replays only hold button presses, so they must be made again whenever the physics or a map
 * changes; `node tests/run.js` checks that each one still reaches its goal.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const SM = require('./sim.js');
const solver = require('./solver.js');

const runs = [];
for (let level = 0; level < SM.Levels.count(); level++) {
  const result = solver.solve(level, { power: 0 });
  if (!result.solved) throw new Error('no route through world ' + SM.Levels.get(level).name + ' was found');
  const bursts = result.bursts.join('');
  const lines = [];
  for (let i = 0; i < bursts.length; i += 80) lines.push("        '" + bursts.slice(i, i + 80) + "'");
  runs.push('      level: ' + level + ',\n      bursts:\n' + lines.join(' +\n') + ',');
  console.log('world ' + SM.Levels.get(level).name + ': ' + bursts.length + ' bursts, ' +
    (result.inputs.length / 60).toFixed(1) + ' s');
}

const source = [
  '/* Generated by tests/make-demo.js: button presses for the demos that play on the title screen. */',
  '(function (SM) {',
  "  'use strict';",
  '',
  '  SM.DEMO = {',
  '    // Each digit of a run picks one of `actions` and holds it for `burstFrames` frames.',
  '    burstFrames: ' + solver.BURST_FRAMES + ',',
  '    actions: [',
  solver.ACTIONS.map(function (a) {
    const keys = Object.keys(a);
    return '      {' + (keys.length ? ' ' + keys.map(function (k) {
      return k + ': true';
    }).join(', ') + ' ' : '') + '},';
  }).join('\n'),
  '    ],',
  '    runs: [',
  runs.map(function (r) {
    return '      {\n' + r.replace(/^ {6}/gm, '        ') + '\n      },';
  }).join('\n'),
  '    ],',
  '  };',
  '})((globalThis.SM = globalThis.SM || {}));',
  '',
].join('\n');

fs.writeFileSync(path.join(__dirname, '..', 'js', 'demo.js'), source);
console.log('wrote js/demo.js');
